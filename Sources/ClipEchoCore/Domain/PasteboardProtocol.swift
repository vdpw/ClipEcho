import Foundation

public enum PasteboardProtocol {
    public static let sourceType = "org.nspasteboard.source"
    public static let remoteType = "com.apple.is-remote-clipboard"
    public static let transientType = "org.nspasteboard.TransientType"
    public static let concealedType = "org.nspasteboard.ConcealedType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    public enum Disposition: Equatable, Sendable { case record, concealed, transient, autoGenerated }
    public struct Assessment: Equatable, Sendable {
        public let disposition: Disposition
        public let sourceBundleID: String?
        public let isRemoteClipboard: Bool
        public var shouldRecord: Bool { disposition == .record }
    }

    /// Call on all item type names before asking NSPasteboard for any payload.
    public static func disposition(forTypes items: [[String]]) -> Disposition {
        let types = Set(items.joined())
        if !types.isDisjoint(with: [concealedType, "com.agilebits.onepassword"]) { return .concealed }
        if !types.isDisjoint(with: [transientType, "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"]) { return .transient }
        if types.contains(autoGeneratedType) { return .autoGenerated }
        return .record
    }

    public static func assess(_ event: ClipboardEvent) -> Assessment {
        let disposition = disposition(forTypes: event.items.map { $0.dataList.map(\.type) })
        guard disposition == .record else { return Assessment(disposition: disposition, sourceBundleID: nil, isRemoteClipboard: false) }
        return Assessment(disposition: .record,
                          sourceBundleID: event.representation(for: sourceType).flatMap { EventCodec.strictUTF8($0.data) },
                          isRemoteClipboard: event.representation(for: remoteType) != nil)
    }

    public static func prepareForRestore(_ event: ClipboardEvent, sourceBundleID: String?, isRemoteClipboard: Bool) throws -> ClipboardEvent {
        guard !event.items.isEmpty else { throw EventCodec.Failure.truncated }
        var output = event
        for index in output.items.indices {
            output.items[index].dataList.removeAll { $0.type == sourceType || $0.type == remoteType }
        }
        output.items[0].dataList.append(ClipboardRepresentation(type: sourceType, data: Data((sourceBundleID ?? "").utf8)))
        if isRemoteClipboard {
            output.items[0].dataList.append(ClipboardRepresentation(type: remoteType, data: Data()))
        }
        return output
    }
}

/// An own-write echo is identified by the exact pasteboard generation. A later
/// foreign write, even of identical bytes, cannot consume this suppression.
public struct RestoreSuppression: Sendable {
    public let changeCount: Int
    public let expiresAt: Date
    public init(changeCount: Int, expiresAt: Date) { self.changeCount = changeCount; self.expiresAt = expiresAt }
    public func suppresses(changeCount: Int, now: Date = Date()) -> Bool {
        self.changeCount == changeCount && now <= expiresAt
    }
}
