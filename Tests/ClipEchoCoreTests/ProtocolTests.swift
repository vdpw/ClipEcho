import Foundation
import Testing
@testable import ClipEchoCore

@Suite struct ProtocolTests {
    private func event(_ values: [(String, Data)]) -> ClipboardEvent {
        ClipboardEvent(items: [ClipboardItem(dataList: values.map { ClipboardRepresentation(type: $0.0, data: $0.1) })])
    }

    @Test func testEventWidePrivacyPreflightUsesPresenceAcrossEveryItem() {
        let markers = [PasteboardProtocol.concealedType, "com.agilebits.onepassword", PasteboardProtocol.transientType, "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type", PasteboardProtocol.autoGeneratedType]
        for marker in markers {
            #expect(PasteboardProtocol.disposition(forTypes: [["public.utf8-plain-text"], [marker]]) != .record)
            let sensitive = ClipboardEvent(items: [ClipboardItem(dataList: [ClipboardRepresentation(type: "public.utf8-plain-text", data: Data("synthetic private fixture".utf8))]), ClipboardItem(dataList: [ClipboardRepresentation(type: marker, data: Data())])])
            #expect(EventClassifier.prepare(event: sensitive, compactMode: false) == nil)
            #expect(EventClassifier.prepare(event: sensitive, compactMode: true) == nil)
            #expect(PasteboardProtocol.assess(sensitive).sourceBundleID == nil)
        }
        #expect(PasteboardProtocol.disposition(forTypes: [[PasteboardProtocol.transientType, PasteboardProtocol.concealedType, PasteboardProtocol.autoGeneratedType]]) == .concealed)
        #expect(PasteboardProtocol.disposition(forTypes: [[PasteboardProtocol.transientType, PasteboardProtocol.autoGeneratedType]]) == .transient)
    }

    @Test func testFirstSourceStrictUTF8AndRemotePresence() {
        let malformed = ClipboardEvent(items: [ClipboardItem(dataList: [ClipboardRepresentation(type: PasteboardProtocol.sourceType, data: Data([255])), ClipboardRepresentation(type: PasteboardProtocol.remoteType, data: Data([0]))]), ClipboardItem(dataList: [ClipboardRepresentation(type: PasteboardProtocol.sourceType, data: Data("com.later".utf8))])])
        #expect(PasteboardProtocol.assess(malformed).sourceBundleID == nil)
        #expect(PasteboardProtocol.assess(malformed).isRemoteClipboard)
        #expect(PasteboardProtocol.assess(event([(PasteboardProtocol.sourceType, Data())])).sourceBundleID == "")
        #expect(PasteboardProtocol.assess(event([])).sourceBundleID == nil)
        #expect(PasteboardProtocol.assess(event([(PasteboardProtocol.sourceType, Data("  com.source  ".utf8))])).sourceBundleID == "  com.source  ")
        #expect(PasteboardProtocol.assess(event([(PasteboardProtocol.sourceType, Data("\u{feff}com.source".utf8))])).sourceBundleID == "\u{feff}com.source")
    }

    @Test func testRestoreCanonicalMarkersAllItemsAndUnknownSource() throws {
        let original = ClipboardEvent(items: [ClipboardItem(dataList: [ClipboardRepresentation(type: "public.file-url", data: Data("file:///tmp/a".utf8)), ClipboardRepresentation(type: PasteboardProtocol.sourceType, data: Data("old".utf8))]), ClipboardItem(dataList: [ClipboardRepresentation(type: "public.file-url", data: Data("file:///tmp/b".utf8)), ClipboardRepresentation(type: PasteboardProtocol.remoteType, data: Data([1])), ClipboardRepresentation(type: PasteboardProtocol.sourceType, data: Data("conflict".utf8))])])
        let restored = try PasteboardProtocol.prepareForRestore(original, sourceBundleID: "com.saved", isRemoteClipboard: true)
        let flavors = restored.items.flatMap(\.dataList)
        #expect(flavors.filter { $0.type == PasteboardProtocol.sourceType }.count == 1)
        #expect(flavors.filter { $0.type == PasteboardProtocol.remoteType }.count == 1)
        #expect(restored.items[0].representation(for: PasteboardProtocol.sourceType)?.data == Data("com.saved".utf8))
        #expect(restored.items[1].representation(for: PasteboardProtocol.sourceType) == nil)
        let unknown = try PasteboardProtocol.prepareForRestore(original, sourceBundleID: nil, isRemoteClipboard: false)
        #expect(unknown.representation(for: PasteboardProtocol.sourceType)?.data == Data())
        #expect(unknown.representation(for: PasteboardProtocol.remoteType) == nil)
        #expect(throws: (any Error).self) { try PasteboardProtocol.prepareForRestore(ClipboardEvent(items: []), sourceBundleID: nil, isRemoteClipboard: false) }
    }

    @Test func testOwnWriteSuppressionCannotDropNextForeignCopy() {
        let now = Date()
        let suppression = RestoreSuppression(changeCount: 42, expiresAt: now.addingTimeInterval(5))
        #expect(suppression.suppresses(changeCount: 42, now: now))
        #expect(!(suppression.suppresses(changeCount: 43, now: now)))
        #expect(!(suppression.suppresses(changeCount: 42, now: now.addingTimeInterval(6))))
    }
}
